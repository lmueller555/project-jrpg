"""Extract authored Rhea expressions and matched transparent ice layers.

The source drawings come from image_gen. This build only extracts equal cells,
normalizes alpha, and registers the ice layers with nearest-neighbor scaling.
No facial expression, pose, linework or crack is generated by this script.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/source/cinematics/ice_reaper_rhea_closeup'
TARGET = ROOT / 'assets/story/ice_reaper_rhea_closeup'
CANVAS = (384, 512)
KEYS = (
    'neutral_closed', 'strain_begin', 'strain_mid', 'strain_peak',
    'opening_01', 'opening_02', 'angry_open', 'angry_hold',
)
EYES = (
    ((152, 143), (201, 126)), ((152, 143), (201, 126)),
    ((152, 143), (201, 126)), ((152, 143), (201, 126)),
    ((151.8, 142.5), (199.3, 125.7)),
    ((151.0, 139.5), (196.8, 124.9)),
    ((150.1, 139.3), (197.2, 124.3)),
    ((149.9, 139.1), (197.2, 123.9)),
)
OPENNESS = (0.0, 0.0, 0.0, 0.0, 0.2, 0.65, 1.0, 1.0)


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build() -> None:
    TARGET.mkdir(parents=True, exist_ok=True)
    (TARGET / 'frames').mkdir(exist_ok=True)
    expression_source = SOURCE / 'expressions_generated.png'
    ice_source = SOURCE / 'ice_layers_generated.png'
    before = {path.name: digest(path) for path in (expression_source, ice_source)}
    expression_sheet = Image.open(expression_source).convert('RGBA')
    ice_sheet = Image.open(ice_source).convert('RGBA')
    if expression_sheet.size != (1536, 1024):
        raise ValueError(f'Unexpected expression atlas: {expression_sheet.size}')
    if ice_sheet.size != (1536, 1024):
        raise ValueError(f'Unexpected ice atlas: {ice_sheet.size}')
    frames = {}
    records = []
    for index, key in enumerate(KEYS):
        x, y = index % 4 * 384, index // 4 * 512
        bounds = (x, y, x + 384, y + 512)
        frame = expression_sheet.crop(bounds)
        # Remove only generated translucent edge haze; the authored silhouette
        # and every authored expression remain unchanged and fully registered.
        frame.putalpha(frame.getchannel('A').point(lambda alpha: 255 if alpha >= 80 else 0))
        filename = f'frames/{key}.png'
        frame.save(TARGET / filename, optimize=True)
        frames[key] = {
            'file': filename,
            'eyes': [list(point) for point in EYES[index]],
            'openness': OPENNESS[index],
            'source_cell': index,
        }
        records.append({'file': filename, 'source_bounds': list(bounds), 'sha256': digest(TARGET / filename)})
    for index, key in enumerate(('ice_back', 'ice_front')):
        layer = ice_sheet.crop((index * 768, 0, (index + 1) * 768, 1024))
        layer = layer.resize(CANVAS, Image.Resampling.NEAREST)
        if key == 'ice_front':
            # The model authored translucent glass. A monotone optical alpha
            # curve keeps its pale face facets readable while retaining thick
            # opaque outer crystal; this introduces no shape or new linework.
            layer.putalpha(layer.getchannel('A').point(lambda a: round(230 * (a / 255) ** 3)))
        else:
            layer.putalpha(layer.getchannel('A').point(lambda a: 255 if a >= 50 else 0))
        layer.save(TARGET / f'{key}.png', optimize=True)
    manifest = {
        'version': 1, 'actor': 'rhea', 'canvas': list(CANVAS),
        'anchor': [192, 512], 'head_center': [185, 132],
        'face_center': [180, 151], 'eyes': [list(p) for p in EYES[-1]],
        'frames': frames, 'sequence': list(KEYS),
        'ice_front': 'ice_front.png', 'ice_back': 'ice_back.png',
        'portrait_registration': 'Uncropped equal cells; torso continues through canvas bottom. Keep bottom below camera viewport.',
        'eye_effect_contract': 'Open eyes use authored green irises. Synchronize gleam to opening_01 through angry_open using each frame eye centers; no emitted eye light during closed frames.',
        'ice_contract': 'Separate rear blue crystal and translucent cracked front glass. Foreground glass overlaps face and shoulders, with source-authored diagonal blade cracks.',
        'authored': True, 'review': 'awaiting_full_scene_review',
    }
    (TARGET / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    provenance = {
        'version': 1, 'generated_with': 'image_gen',
        'sources': [{'file': path.relative_to(ROOT).as_posix(), 'sha256': before[path.name], 'size': list(Image.open(path).size)} for path in (expression_source, ice_source)],
        'references': [
            'assets/story/ice_reaper_rescue/actors/rhea/eyes_01.png',
            'assets/combat/rhea/spritesheet.png',
            'assets/story/ice_reaper_opening/ice_prison_front.png',
        ],
        'operation': 'Eight separately authored expressions: equal-cell extraction and alpha threshold only. Ice: equal-panel extraction, nearest-neighbor half scaling, monotone alpha remap for glass readability. No procedural facial deformation or new painted linework.',
        'source_unchanged': all(digest(path) == before[path.name] for path in (expression_source, ice_source)),
        'frames': records,
        'exports': {path.relative_to(TARGET).as_posix(): digest(path) for path in sorted(TARGET.rglob('*.png'))},
        'review': 'awaiting_full_scene_review',
    }
    (TARGET / 'provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')
    print(json.dumps({'canvas': list(CANVAS), 'expressions': len(frames), 'source_unchanged': provenance['source_unchanged']}))


if __name__ == '__main__':
    build()
