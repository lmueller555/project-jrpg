def carry(dr,i,can=False):
 k=KEYS[dr][i];b=k['bob'];arms=grips(dr,can);im=Image.new('RGBA',(48,72));d=ImageDraw.Draw(im)
 for key,color in ([('fb','#5d402e'),('nb',B)] if dr in ('right','left') else [('lb',B),('rb','#5d402e')]):poly(d,k[key],color);d.line(k[key][1:3],fill=BL)
 if dr=='back':
  # The forearms/grip are on the unseen front, correctly hidden by the torso.
  for arm in (arms[0],arms[2]):poly(d,q(arm,b),C)
 else:poly(d,q(arms[0],b),S);poly(d,q(arms[1],b),SH)
 poly(d,k['dress'],C);dress_detail(d,k,dr,b)
 if dr=='front':
  for arm,color in zip(arms,(C,SK,C,SK)):poly(d,q(arm,b),color)
 elif dr!='back':poly(d,q(arms[2],b),C);d.line(q(arms[2][1:3],b),fill=L);poly(d,q(arms[3],b),SK)
 im.alpha_composite(REF[dr].crop((0,0,48,28)),(0,b))
 return im

